// Convert the detailed tables of docs/paper/attempts.md into a LaTeX appendix
// (docs/paper/appendix-attempts.tex). Usage: node docs/paper/attempts2tex.mjs
import { readFileSync, writeFileSync } from 'node:fs';

const dir = new URL('.', import.meta.url);
const md = readFileSync(new URL('attempts.md', dir), 'utf8');

const SYMBOLS = { '≥': '$\\ge$', '≤': '$\\le$', '×': '$\\times$', '−': '$-$', '→': '$\\to$', 'α': '$\\alpha$', '∞': '$\\infty$', '′': "$'$", '…': '\\dots{}', '≈': '$\\approx$', '–': '--', '—': '---', '·': '$\\cdot$', '∈': '$\\in$' };
const esc = s => s.replace(/[\\{}$&%#_^~]/g, c => ({ '\\': '\\textbackslash{}', '{': '\\{', '}': '\\}', '$': '\\$', '&': '\\&', '%': '\\%', '#': '\\#', '_': '\\_', '^': '\\^{}', '~': '\\~{}' }[c]))
  .replace(/[≥≤×−→α∞′…≈–—·∈]/g, c => SYMBOLS[c]);
// Inline markdown: `code`, **bold**, escaped pipes.
function cell(s) {
  s = s.trim().replace(/\\\|/g, '|');
  // Code spans become placeholders first, so **bold** may wrap them.
  const code = [];
  s = s.replace(/`([^`]*)`/g, (_, c) => { code.push(`\\texttt{${esc(c).replace(/\|/g, '$|$').replace(/--/g, '\\textendash{}').replace(/([-/.])/g, '$1\\allowbreak{}')}}`); return `\u0000${code.length - 1}\u0000`; });
  s = esc(s).replace(/\|/g, '$|$').replace(/\*\*([^*]+)\*\*/g, '\\textbf{$1}');
  return s.replace(/\u0000(\d+)\u0000/g, (_, i) => code[+i]);
}

const sections = [];
let cur = null;
for (const line of md.split('\n')) {
  const h = line.match(/^### (.*)$/);
  if (h) { cur = { title: h[1].replace(/^\d+\.\s*/, ''), rows: [], intro: [] }; sections.push(cur); continue; }
  if (!cur) continue;
  if (line.startsWith('|') && !/^\|\s*-/.test(line)) {
    const cells = line.slice(1, -1).split(/(?<!\\)\|/).map(c => c.trim());
    if (cells[0] === 'Goal' || cells[0] === 'Level / Design') continue; // header row
    cur.rows.push(cells);
  } else if (line.startsWith('Primary sources') || line.startsWith('Note')) cur.intro.push(line);
}

let tex = `% Generated by docs/paper/attempts2tex.mjs from docs/paper/attempts.md. Do not edit.
\\section{Forking-paths ledger}
\\label{app:attempts}
This appendix lists every design loop, amendment, headroom screen, diagnostic and fresh-seed final in the Microverse line (commits \\texttt{d459944} to \\texttt{16b4372}), so that each pass can be read against the attempts that preceded it. Failed and superseded attempts are kept. Practice seeds were 101--116 and 301--332; fresh banks were each run once. The verification banks of Section~\\ref{sec:verification} (6100001--6100048 and 6200001--6200096) were also spent once, after this ledger closed, as were the banks of the revision experiments E1 and E2 (6300001--6300048 and 6400001--6400096).
`;
for (const s of sections.filter(s => s.rows.length)) {
  tex += `
\\subsection{${esc(s.title)}}
${s.intro.map(cell).join(' ')}
{\\footnotesize\\setlength{\\tabcolsep}{3pt}\\renewcommand{\\arraystretch}{1.15}
\\begin{longtable}{@{}>{\\raggedright\\arraybackslash}p{1.75cm}>{\\raggedright\\arraybackslash}p{2.6cm}>{\\raggedright\\arraybackslash}p{4.3cm}>{\\raggedright\\arraybackslash}p{4.75cm}>{\\raggedright\\arraybackslash}p{2.15cm}@{}}
\\toprule
\\textbf{Goal} & \\textbf{Step (commit)} & \\textbf{Change} & \\textbf{Outcome} & \\textbf{Seeds} \\\\
\\midrule
\\endhead
`;
  for (const [goal, step, commit, change, outcome, seeds] of s.rows)
    tex += `${cell(goal)} & ${cell(step)} (${cell(commit)}) & ${cell(change)} & ${cell(outcome)} & ${cell(seeds)} \\\\\n`;
  tex += `\\bottomrule\n\\end{longtable}}\n`;
}
writeFileSync(new URL('appendix-attempts.tex', dir), tex);
